export function getReviewsForCollection(collectionId) {
  if (!collectionId) return reviews;
  return reviews.filter((r) => !r.collection || r.collection === collectionId);
}

export function getAverageRating(list = reviews) {
  if (list.length === 0) return 0;
  return list.reduce((sum, r) => sum + r.rating, 0) / list.length;
}
